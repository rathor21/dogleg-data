def _driver_source_text(what, margin, unit):
    return (f"TrackMan Carry Optimizer 2010 and PING 2019, read at the current club speed, ball speed and attack "
            f"angle (values in detail). Band runs from the lower source minus {margin:g} {unit} to the higher plus "
            f"{margin:g} {unit} (MODELED margin).")


def _split_sources(bands):
    """Move each band's source string into a shared sources dict. Returns
    (sources, bands) where every band has source_id and no source. The source
    id is the exported metric name, with a driver id for the two optimizer
    metrics. The text must be identical for every band that uses an id."""
    sources = {}
    tol = data.IDEAL_TOL
    out = {}
    for player, clubs in bands.items():
        out[player] = {}
        for club, metrics in clubs.items():
            out[player][club] = {}
            for metric, band in metrics.items():
                name = METRIC_NAMES.get(metric, metric)
                band = dict(band)
                text = band.pop("source")
                sid = name
                if club == "driver" and metric in ("attack_deg", "dyn_loft_deg"):
                    sid = name + "_driver"
                    text = ideals.DRIVER_ATTACK_SOURCE if metric == "attack_deg" else ideals.DRIVER_LOFT_SOURCE
                if club == "driver" and metric in ("launch_deg", "spin_rpm"):
                    sid = name + "_driver"
                    text = _driver_source_text(
                        metric, tol["driver_launch_margin_deg"] if metric == "launch_deg" else tol["driver_spin_margin_rpm"],
                        "deg" if metric == "launch_deg" else "rpm")
                if sources.setdefault(sid, text) != text:
                    raise RuntimeError(f"source text for {sid} differs between bands")
                band["source_id"] = sid
                out[player][club][name] = band
    return sources, out


