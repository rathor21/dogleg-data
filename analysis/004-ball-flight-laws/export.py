def _trajectory(f):
    n = len(f.t)
    idx = list(range(0, n, TRAJECTORY_STRIDE))
    if idx[-1] != n - 1:
        idx.append(n - 1)  # always keep the landing sample
    return {
        "stride": TRAJECTORY_STRIDE,
        "indices": idx,
        "t": [float(f.t[i]) for i in idx],
        "x": [float(f.x[i]) for i in idx],
        "y": [float(f.y[i]) for i in idx],
        "z": [float(f.z[i]) for i in idx],
    }


def _classify_vectors():
    """Pure classify() vectors on a 200 yd carry for the JS classifier: every
    start, shape and finish (on target and off) plus the threshold edges."""
    shapes = ((0.0, 0.0), (-5.0, -10.0), (5.0, 10.0), (-10.0, -32.0), (10.0, 32.0), (1.9, 40.0), (-2.0, -10.0), (2.0001, 10.0))
    starts = (-3.0, -2.0001, -2.0, 0.0, 2.0, 2.0001, 3.0)
    sides = (-40.0, -8.5, -8.0, -2.0, 0.0, 0.9, 1.0, 8.0, 8.5, 40.0)
    out = []
    for start in starts:
        for axis, curve in shapes:
            for side in sides:
                args = [start, axis, curve, side, 200.0]
                out.append({"args": args, "result": classify.classify(*args)})
    return out


def _optimal_loft_vectors():
    """optimal_loft() at club speeds inside, on and outside the chart's 75 to 120
    mph and attack angles inside, on and outside its -5 to +5, for the JS port."""
    out = []
    for speed in (60.0, 75.0, 82.5, 94.0, 100.0, 115.0, 120.0, 135.0):
        for attack in (-8.0, -5.0, -2.5, 0.0, 2.0, 4.0, 5.0, 7.5, 10.0):
            r = chart.optimal_loft(speed, attack)
            out.append({"args": [speed, attack], "result": {
                "dyn_loft_deg": r.dyn_loft_deg, "carry_loft_deg": r.carry_loft_deg, "total_loft_deg": r.total_loft_deg,
                "extrapolated": r.extrapolated, "speed_clamped": r.speed_clamped}})
    return out


def build_golden(all_windows):
    with open(gl.GOLDEN_PATH, encoding="utf-8") as fh:
        base = json.load(fh)
    cases = []
    for case in base["cases"]:
        speed, attack, path, face, dyn_loft, club = case["args"]
        trim = case["kwargs"].get("spin_trim", 1.0)
        ln = launch.deliver(speed, attack, path, face, dyn_loft, club, spin_trim=trim)
        f = flight.simulate(ln.ball_speed_mph, ln.launch_deg, ln.launch_dir_deg, ln.spin_rpm, ln.spin_axis_deg, dt=base["dt"])
        entry = {
            "id": case["id"],
            "delivery": {"club_speed_mph": speed, "attack_deg": attack, "path_deg": path, "face_deg": face,
                         "dyn_loft_deg": dyn_loft, "club": club, "spin_trim": trim},
            "launch": case["launch"],
            "flight": dict(case["flight"], total_yd=flight.roll(f)),
            # classify() raises for a carry of zero (edge_loft_zero launches downward), so the fixture holds null.
            "classification": (classify.classify(ln.launch_dir_deg, ln.spin_axis_deg, f.curve_yd, f.side_yd, f.carry_yd)
                               if f.carry_yd > 0.0 else None),
        }
        if case["id"] in TRAJECTORY_CASES:
            entry["trajectory"] = _trajectory(f)
        cases.append(entry)
    have = {c["id"] for c in cases if "trajectory" in c}
    if have != set(TRAJECTORY_CASES):
        raise RuntimeError(f"trajectory cases missing from golden_launch.json: {sorted(set(TRAJECTORY_CASES) - have)}")
    return {
        "note": "JS parity fixture. cases: tests/golden_launch.json deliveries, launch outputs and flight summaries "
                "(total_yd added), classify() output for every case and sampled trajectories (steps 0, 10, 20 and "
                "the landing step) for 12. classify_vectors: pure classify() inputs (launch dir, spin axis, curve, "
                "side, carry) and outputs. optimal_loft_vectors: chart.optimal_loft inputs and outputs. Rounded to 9 significant digits. windows_pga_7i: the nine PGA 7-iron "
                "recipes.",
        "sig_digits": GOLDEN_SIG,
        "dt": base["dt"],
        "cases": cases,
        "classify_vectors": _classify_vectors(),
        "optimal_loft_vectors": _optimal_loft_vectors(),
        "windows_pga_7i": {f"{w['height']}_{w['shape']}": w for w in all_windows["pga"]},
    }


