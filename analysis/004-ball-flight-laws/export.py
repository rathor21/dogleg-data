def _published_rows():
    """{player: {club: row}}, lowercase player ids. Dynamic and spin loft join
    the tour rows where TrackMan publishes them (driver and 6-iron)."""
    out = {}
    for player, tour in (("pga", "PGA"), ("lpga", "LPGA")):
        rows = {}
        for club, r in data.TOURS[tour].items():
            row = dict(r)
            if (tour, club) in data.DYNAMIC_LOFT_DEG:
                row["dyn_loft_deg"] = data.DYNAMIC_LOFT_DEG[(tour, club)]
                row["spin_loft_deg"] = data.SPIN_LOFT_DEG[(tour, club)]
            rows[club] = row
        out[player] = rows
    out["amateur"] = {c: dict(a) for c, a in data.AMATEUR_ANCHORS.items()}
    return out


def build_presets():
    out_presets = {}
    for player in presets.PLAYERS:
        out_presets[player] = {}
        for club in presets.CLUBS:
            p = presets.preset(club, player)
            ln, f = presets.fly(p)
            entry = {DELIVERY_NAMES.get(k, k): v for k, v in p.items() if k != "ideal"}
            entry["at_preset"] = {"launch": launch_summary(ln), "flight": flight_summary(f)}
            ideal = {DELIVERY_NAMES.get(k, k): v for k, v in p["ideal"].items()}
